/**
 * Выгружает дикторский текст в output/narration-ru.txt.
 * Источник правды — NARRATION_RU и SUBTITLES в src/data/subtitles.ts,
 * поэтому файл всегда соответствует таймингу ролика.
 *
 * Запуск: node --experimental-strip-types scripts/write-narration.mjs
 */
import {mkdirSync, writeFileSync} from 'node:fs';
import path from 'node:path';
import {NARRATION_RU, SUBTITLES} from '../src/data/subtitles.ts';
import {FPS} from '../src/data/timeline.ts';

const OUT_DIR = path.join(process.cwd(), 'output');
mkdirSync(OUT_DIR, {recursive: true});

const timecode = (frame) => {
  const total = frame / FPS;
  const m = Math.floor(total / 60);
  const s = total - m * 60;
  return `${String(m).padStart(2, '0')}:${s.toFixed(1).padStart(4, '0')}`;
};

const cues = SUBTITLES.map((cue) => {
  const from = timecode(cue.from);
  const to = timecode(cue.from + cue.durationInFrames);
  return `${from} — ${to}\n${cue.lines.join('\n')}`;
}).join('\n\n');

const text = `ВТОРОЙ КАНОН · @vtoroy.kanon
К2 · I · М-002 — «Почему сердце сокращается само? Автоматизм синусового узла»
Вертикальный ролик 1080×1920, 30 fps.

────────────────────────────────────────────────────────────
ДИКТОРСКИЙ ТЕКСТ (сплошной)
────────────────────────────────────────────────────────────

${NARRATION_RU}

────────────────────────────────────────────────────────────
СУБТИТРЫ ПО ТАЙМКОДУ (как в ролике)
────────────────────────────────────────────────────────────

${cues}

────────────────────────────────────────────────────────────
ПРИМЕЧАНИЯ ДЛЯ ОЗВУЧКИ И РЕДАКТУРЫ
────────────────────────────────────────────────────────────

1. Ролик смонтирован без озвучки: смысл полностью читается по субтитрам
   и визуальному ритму. При записи живого голоса ориентируйтесь на
   таймкоды выше — они совпадают с появлением субтитров.
2. Iᶠ произносится как «ток и-эф»; это смешанный ток Na⁺/K⁺ через
   HCN-каналы с результирующим входящим влиянием, а не «натриевый ток».
3. Зубец P отражает деполяризацию миокарда предсердий, а не самого узла.
4. Фаза 0 в клетках синусового узла обусловлена входом Ca²⁺ через каналы
   L-типа; быстрые натриевые каналы здесь не являются главным механизмом.
5. Две финальные фразы («Сердце получает влияние извне. / Но первый импульс
   рождается внутри него.») намеренно не продублированы субтитрами: они
   выведены на кадр крупным планом как утверждение, поэтому их нет в списке
   таймкодов выше.
6. Перед публикацией материал должен быть сверен медицинским редактором
   проекта («Второй читатель»), как того требует редакционный регламент.
`;

const out = path.join(OUT_DIR, 'narration-ru.txt');
writeFileSync(out, text, 'utf8');
console.log(`Записано: ${path.relative(process.cwd(), out)} (${text.length} символов)`);
